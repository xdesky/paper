test('production workspace preserves auto-update, print switches, and English PDF exports',async({page,context})=>{
 const request=context.request;
 await context.addInitScript(()=>{window.print=()=>{};});
 const p=await(await request.post('/api/projects',{data:{name:'Holiday Cottage',preset:'gb_classic',paper:'US Letter'}})).json();
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 try{
  await page.goto('/');await page.locator('.project-list button').filter({hasText:p.name}).click();
  await page.getByRole('group',{name:'Roof pattern',exact:true}).getByRole('button',{name:'Choose Snowflakes',exact:true}).click();
  await expect.poll(async()=> (await(await request.get(`/api/projects/${p.id}`)).json()).status,{timeout:45000}).toBe('READY');
  await expect(page.locator('.svg-sheet svg').first()).toBeVisible({timeout:20000});
  const printStyle=page.getByRole('switch',{name:'Print style',exact:true});
  await printStyle.click();
  await expect(page.locator('.svg-sheet svg').first()).toHaveAttribute('data-print-style','coloring');
  const [popup]=await Promise.all([page.waitForEvent('popup'),page.getByRole('link',{name:'⎙ Print',exact:true}).click()]);
  await expect(popup.locator('html')).toHaveAttribute('lang','en-US');
  expect(vietnamese.test(await popup.locator('body').innerText())).toBeFalsy();await popup.close();
  const paper=page.getByRole('switch',{name:'Paper format',exact:true});
  await paper.click();
  await expect.poll(async()=>{const data=await(await request.get(`/api/projects/${p.id}`)).json();return data.status==='READY'&&data.paper==='A4';},{timeout:45000}).toBeTruthy();
  await expect(page.locator('.svg-sheet svg').first()).toHaveAttribute('width','210.0mm');
  await expect(page.locator('.model-view canvas')).toBeVisible();
  await page.locator('.thumbnail-choice').first().scrollIntoViewIfNeeded();
  await expect.poll(()=>page.locator('.thumbnail-choice img').first().evaluate((img:HTMLImageElement)=>img.complete&&img.naturalWidth>0)).toBeTruthy();
  expect(await page.locator('.workspace').evaluate(e=>getComputedStyle(e).gap)).toBe('20px');
  await page.screenshot({path:'../test-results/production-workspace.png',fullPage:false});
  await page.getByRole('button',{name:'▤ My projects',exact:true}).click();
  await expect(page.locator('.sidebar').getByRole('button',{name:'Downloads',exact:true})).toHaveCount(0);
  await expect(page.locator('.sidebar').getByRole('button',{name:'Let’s create',exact:true})).toHaveCount(0);
  await expect(page.locator('.home-create').getByRole('button',{name:'Let’s create',exact:true})).toBeVisible();
  await expect(page.locator('.home-create').getByRole('button',{name:'Browse templates',exact:true})).toBeVisible();
  const card=page.locator('.saved-project').filter({hasText:p.name});
  await card.getByRole('button',{name:'Downloads',exact:true}).click();
  const downloads=card.getByRole('region',{name:`Downloads for ${p.name}`});
  await expect(downloads.getByRole('link',{name:'Download PDF',exact:true})).toBeVisible();
  await downloads.getByRole('switch',{name:'Print style'}).click();
  await expect(downloads.getByRole('link',{name:'Download PDF',exact:true})).toHaveAttribute('href',`/api/projects/${p.id}/artifacts/printable_a4_coloring.pdf?download=true`);
  const pdf=await request.get((await downloads.getByRole('link',{name:'Download PDF',exact:true}).getAttribute('href'))!);
  expect(pdf.status()).toBe(200);expect(pdf.headers()['content-type']).toBe('application/pdf');
  await expect(downloads.getByRole('link',{name:'Download all (ZIP)',exact:true})).toBeVisible();
  await page.screenshot({path:'../test-results/project-downloads.png',fullPage:false});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  expect(errors).toEqual([]);
 }finally{await request.delete(`/api/projects/${p.id}`);}
});
