import {test,expect} from '@playwright/test';
test('account registration, saved projects, sign-out and return',async({page})=>{
 const email=`browser-${Date.now()}@example.com`,password='browser-test-password';
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await expect(page.getByRole('button',{name:/Quality checks/})).toHaveCount(0);
 await page.getByRole('button',{name:'Sign in or create an account'}).click();
 await page.getByRole('button',{name:'Create account',exact:true}).last().click();
 await page.getByLabel('Your name', {exact:true}).fill('Holiday Maker');
 await page.getByLabel('Email address').fill(email);
 await page.getByLabel('Password',{exact:true}).fill(password);
 await page.getByRole('button',{name:'Create account',exact:true}).last().click();
 await expect(page.getByText('Starter account',{exact:true})).toBeVisible();
 await expect(page.getByText('Purchases are not available yet.',{exact:false})).toBeVisible();
 await page.screenshot({path:'../test-results/account-desktop.png'});
 await page.getByRole('button',{name:'＋ New project',exact:true}).click();
 await page.getByLabel('Project name',{exact:true}).fill('Saved holiday house');
 await page.getByRole('button',{name:'Create project',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Saved holiday house',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'▤ My projects',exact:true}).click();
 await expect(page.locator('.saved-project')).toHaveCount(1);
 await page.getByRole('button',{name:'Duplicate',exact:true}).click();
 await expect(page.locator('.saved-project')).toHaveCount(2);
 await page.screenshot({path:'../test-results/saved-projects.png'});
 await page.getByRole('button',{name:'○ Account',exact:true}).click();
 await expect(page.getByText('2 saved projects',{exact:false})).toBeVisible();
 await page.getByRole('button',{name:'Sign out',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Welcome back'})).toBeVisible();
 await page.getByLabel('Email address').fill(email);
 await page.getByLabel('Password',{exact:true}).fill(password);
 await page.getByRole('button',{name:'Sign in',exact:true}).last().click();
 await expect(page.getByText('Starter account',{exact:true})).toBeVisible();
 await page.reload();
 await page.getByRole('button',{name:'▤ My projects',exact:true}).click();
 await expect(page.locator('.saved-project')).toHaveCount(2);
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await page.getByRole('button',{name:'○ Account',exact:true}).click();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await page.screenshot({path:'../test-results/account-mobile.png',fullPage:true});
 // Clean up only projects created by this test account.
 const projects=await(await page.request.get('/api/projects')).json();
 for(const p of projects)await page.request.delete(`/api/projects/${p.id}`);
 expect(errors).toEqual([]);
});
